/// Source guards over segment-match (decisions § 2392): what a fake client
/// cannot see. The gate order, the platform config, and that the matcher the
/// function runs is the generated bundle of the web module rather than a copy.
///
/// Run with `cd apps/backend && deno test --allow-read supabase/functions/segment-match/wiring.test.ts`.

import { assert } from 'https://deno.land/std@0.224.0/assert/mod.ts';

const HANDLER = await Deno.readTextFile(new URL('./handler.ts', import.meta.url));
const LIB = await Deno.readTextFile(new URL('./lib.ts', import.meta.url));
const INDEX = await Deno.readTextFile(new URL('./index.ts', import.meta.url));
const CONFIG = await Deno.readTextFile(new URL('../../config.toml', import.meta.url));
const BUNDLE = await Deno.readTextFile(new URL('../_shared/segment_matcher.generated.js', import.meta.url));

Deno.test('gates run in order: method, server key, body, then any read', () => {
  const at = {
    method: HANDLER.indexOf("{ error: 'method_not_allowed' }, { status: 405 }"),
    unconfigured: HANDLER.indexOf("{ error: 'not_configured' }, { status: 503 }"),
    forbidden: HANDLER.indexOf("{ error: 'forbidden' }, { status: 403 }"),
    body: HANDLER.indexOf('readJsonWithLimit(req, MAX_BODY_BYTES)'),
    client: HANDLER.indexOf('const client = deps.serviceClient();'),
  };
  for (const [name, i] of Object.entries(at)) assert(i >= 0, `${name} not found in the handler`);
  assert(at.method < at.unconfigured && at.unconfigured < at.forbidden);
  assert(at.forbidden < at.body, 'the body is not read for a caller without a server key');
  assert(at.body < at.client, 'no database read happens before the gate and the payload pass');
});

Deno.test('the platform gate is off for segment-match, and the key gate is the way in', () => {
  assert(/\[functions\.segment-match\]\s*\nverify_jwt = false/.test(CONFIG));
  assert(LIB.includes('timingSafeEqual(presented, k)'), 'the key compare must be constant-time');
  assert(INDEX.includes('createClient<Database>(Deno.env.get(\'SUPABASE_URL\')!, secretKey())'));
});

Deno.test('the matcher is the generated bundle of the web module', () => {
  assert(BUNDLE.startsWith('// GENERATED by scripts/gen_edge_segment_matcher.mjs'));
  assert(BUNDLE.includes('// apps/web/src/lib/segments/segments.ts'));
  assert(LIB.includes("from '../_shared/segment_matcher.generated.js'"));
  assert(!/function\s+computeGlobalSegmentEfforts/.test(LIB), 'no hand copy of the matcher in the function');
});
