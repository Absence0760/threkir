#!/usr/bin/env node
// Write apps/web/src/lib/share/grisnir_badge_data.ts from the rendered head
// crop (grisnir-head-256.png: the unfurls draw him small, where the whole
// goat reads as a white blob), so a share card built as an SVG string can
// embed Grisnir as a data URI
// (resvg in the share Lambdas loads no files). `--check` fails when the
// module and the PNG disagree; apps/web/src/lib/share/grisnir_badge.test.ts
// pins the same in CI.
//
//   node scripts/brand/gen_grisnir_badge_module.mjs [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const BADGE_PNG = join(ROOT, 'apps/web/static/brand/grisnir/grisnir-head-256.png');
export const BADGE_MODULE = join(ROOT, 'apps/web/src/lib/share/grisnir_badge_data.ts');

/** @param {Buffer} png */
export function pngSize(png) {
	if (png.toString('ascii', 1, 4) !== 'PNG') throw new Error('not a PNG');
	return { width: png.readUInt32BE(16), height: png.readUInt32BE(20) };
}

/** @param {Buffer} png */
export function badgeModuleSource(png) {
	const { width, height } = pngSize(png);
	return [
		'// Generated by scripts/brand/gen_grisnir_badge_module.mjs from',
		'// apps/web/static/brand/grisnir/grisnir-head-256.png. Do not edit.',
		'',
		`export const GRISNIR_BADGE_WIDTH = ${width};`,
		`export const GRISNIR_BADGE_HEIGHT = ${height};`,
		`export const GRISNIR_BADGE_PNG_BASE64 =\n\t'${png.toString('base64')}';`,
		'',
	].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const want = badgeModuleSource(readFileSync(BADGE_PNG));
	if (process.argv.includes('--check')) {
		if (readFileSync(BADGE_MODULE, 'utf8') !== want) {
			console.error('grisnir_badge_data.ts is stale: run node scripts/brand/gen_grisnir_badge_module.mjs');
			process.exit(1);
		}
	} else {
		writeFileSync(BADGE_MODULE, want);
	}
}
