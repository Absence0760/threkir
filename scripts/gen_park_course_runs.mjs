#!/usr/bin/env node
// Writes the park-course run net's two generated artefacts (issue #1342 step
// 5c):
//
//   fixtures/park_course_runs.json
//       synthetic runs over the six Pocahontas courses and what the matcher
//       gives each, from apps/web/src/lib/parks/course_run_fixture.ts. Read by
//       the web, Dart and Edge Function tests.
//   apps/backend/supabase/tests/park_course_boards_test.sql (one block)
//       the Pocahontas catalogue payload exactly as the release sync hands it
//       to private.load_park_catalogue (scripts/parks/lib/catalogue_payload.mjs),
//       the lines the fixture times each course by, and the matcher's efforts
//       per run, between the GENERATED markers. The rest of the file is
//       written by hand.
//
// The generator module is TypeScript that imports the web matcher, so it is
// bundled with apps/web's esbuild in memory, as gen_edge_segment_matcher.mjs
// bundles the matcher. apps/web/src/lib/parks/course_run_fixture.test.ts
// rebuilds both outputs and fails the web unit suite when either is stale.
//
//   node scripts/gen_park_course_runs.mjs           rewrite both
//   node scripts/gen_park_course_runs.mjs --check   exit 1 if either is stale

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { cataloguePayload } from './parks/lib/catalogue_payload.mjs';

export const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const FIXTURE = join(REPO_ROOT, 'fixtures', 'park_course_runs.json');
export const SQL_TEST = join(REPO_ROOT, 'apps', 'backend', 'supabase', 'tests', 'park_course_boards_test.sql');
const PARK_DIR = join(REPO_ROOT, 'scripts', 'parks', 'catalogue', 'us-va', 'pocahontas');
const GENERATOR = join(REPO_ROOT, 'apps', 'web', 'src', 'lib', 'parks', 'course_run_fixture.ts');

export const BEGIN = '-- >>> GENERATED by scripts/gen_park_course_runs.mjs: do not edit; run `pnpm gen:park-course-runs`';
export const END = '-- <<< END GENERATED';

/** @param {string} path a path from the repo root */
export function readRepo(path) {
	return readFileSync(join(REPO_ROOT, path), 'utf8');
}

/**
 * @typedef {{ time_seconds: number, started_offset_ms: number, matched_by: string }} Effort
 * @typedef {{ lat: number, lng: number, bearing_deg: number, half_width_m: number, source: string }} Line
 * @typedef {{
 *   courses: { slug: string, start_gate: Line, end_gate: Line }[],
 *   cases: { key: string, course: string, matched: Record<string, Effort>,
 *            extent: { min_lat: number, min_lng: number, max_lat: number, max_lng: number } }[],
 * }} Fixture
 */

/** @returns {Promise<{ buildCourseRunFixture(read: (p: string) => string): Fixture, formatFixture(v: unknown): string }>} */
async function loadGenerator() {
	const require = createRequire(join(REPO_ROOT, 'apps', 'web', 'package.json'));
	/** @type {{ build(o: Record<string, unknown>): Promise<{ outputFiles: { text: string }[] }> }} */
	const esbuild = require('esbuild');
	const result = await esbuild.build({
		entryPoints: [GENERATOR],
		bundle: true,
		format: 'esm',
		platform: 'neutral',
		target: 'es2022',
		write: false,
		legalComments: 'none',
		charset: 'utf8',
		tsconfigRaw: {},
		absWorkingDir: REPO_ROOT,
	});
	const url = `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`;
	return import(url);
}

/** The Pocahontas payload as the release sync builds it. */
export function pocahontasPayload() {
	const manifest = JSON.parse(readFileSync(join(PARK_DIR, 'manifest.json'), 'utf8'));
	return cataloguePayload(manifest, (file) => JSON.parse(readFileSync(join(PARK_DIR, file), 'utf8')));
}

/** @param {unknown} v */
const sqlText = (v) => `'${String(v).replaceAll("'", "''")}'`;
/** @param {number} v */
const sqlNum = (v) => {
	if (!Number.isFinite(v)) throw new Error(`not a finite number: ${v}`);
	return String(v);
};

/**
 * The generated block of park_course_boards_test.sql: three temp tables the
 * hand-written assertions read.
 *
 * @param {Fixture} fixture
 * @param {ReturnType<typeof pocahontasPayload>} payload
 */
export function renderSqlBlock(fixture, payload) {
	const json = JSON.stringify(payload);
	if (json.includes('$payload$')) throw new Error('the payload holds the dollar-quote tag');
	const { courses, ...head } = payload;
	const payloadText = [
		'{',
		...Object.entries(head).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)},`),
		'"courses": [',
		courses.map((c) => JSON.stringify(c)).join(',\n'),
		']}',
	].join('\n');
	const gateRows = fixture.courses.map((c) => {
		const s = c.start_gate;
		const e = c.end_gate;
		return `  (${[sqlText(c.slug), sqlNum(s.lat), sqlNum(s.lng), sqlNum(s.bearing_deg), sqlNum(s.half_width_m), sqlText(s.source), sqlNum(e.lat), sqlNum(e.lng), sqlNum(e.bearing_deg), sqlNum(e.half_width_m), sqlText(e.source)].join(', ')})`;
	});
	const runRows = fixture.cases.map((c) => {
		const efforts = Object.entries(c.matched).map(([slug, e]) => ({
			slug,
			time_seconds: e.time_seconds,
			started_offset_ms: e.started_offset_ms,
			matched_by: e.matched_by,
		}));
		const x = c.extent;
		return `  (${[sqlText(c.key), sqlText(c.course), sqlNum(x.min_lat), sqlNum(x.min_lng), sqlNum(x.max_lat), sqlNum(x.max_lng), `${sqlText(JSON.stringify(efforts))}::jsonb`].join(', ')})`;
	});
	return [
		BEGIN,
		'-- The Pocahontas catalogue as private.load_park_catalogue receives it from the',
		'-- release sync, the lines fixtures/park_course_runs.json times each course by,',
		"-- and the matcher's efforts for each synthetic run (started_offset_ms is from",
		"-- the run's first fix).",
		'create temp table pcb_payload (j jsonb not null);',
		`insert into pcb_payload (j) values ($payload$${payloadText}$payload$::jsonb);`,
		'create temp table pcb_lines (',
		'  slug text primary key,',
		'  start_lat float8, start_lng float8, start_bearing_deg float8, start_half_width_m float8, start_source text,',
		'  end_lat float8, end_lng float8, end_bearing_deg float8, end_half_width_m float8, end_source text);',
		'insert into pcb_lines values',
		`${gateRows.join(',\n')};`,
		'create temp table pcb_runs (',
		'  key text primary key, course text not null,',
		'  min_lat float8, min_lng float8, max_lat float8, max_lng float8, efforts jsonb not null);',
		'insert into pcb_runs values',
		`${runRows.join(',\n')};`,
		END,
	].join('\n');
}

/**
 * @param {string} sql the test file
 * @param {string} block a fresh generated block
 */
export function spliceBlock(sql, block) {
	const from = sql.indexOf(BEGIN);
	const to = sql.indexOf(END);
	if (from < 0 || to < from) throw new Error(`${SQL_TEST} has no GENERATED block to replace`);
	return sql.slice(0, from) + block + sql.slice(to + END.length);
}

/** @returns {Promise<{ fixture: string, sql: string }>} both files' full contents */
export async function buildOutputs() {
	const gen = await loadGenerator();
	const fixture = gen.buildCourseRunFixture(readRepo);
	return {
		fixture: `${gen.formatFixture(fixture)}\n`,
		sql: spliceBlock(readFileSync(SQL_TEST, 'utf8'), renderSqlBlock(fixture, pocahontasPayload())),
	};
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const next = await buildOutputs();
	const stale = [
		[FIXTURE, next.fixture],
		[SQL_TEST, next.sql],
	].filter(([path, text]) => {
		try {
			return readFileSync(path, 'utf8') !== text;
		} catch {
			return true;
		}
	});
	if (process.argv.includes('--check')) {
		if (stale.length > 0) {
			for (const [path] of stale) console.error(`${path} is stale.`);
			console.error('Run: pnpm gen:park-course-runs (node scripts/gen_park_course_runs.mjs) and commit both files.');
			process.exit(1);
		}
		console.log('park course runs are current');
	} else {
		for (const [path, text] of stale) {
			writeFileSync(path, text);
			console.log(`wrote ${path}`);
		}
		if (stale.length === 0) console.log('park course runs are current');
	}
}
