import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';

import { DEFAULT_SITE_URL, siteOrigin } from '../core/site_url';
import { buildRobotsTxt, ROBOTS_DISALLOW } from './robots';

const webRoot = resolve(new URL('.', import.meta.url).pathname, '../../..');

function directives(body: string): string[] {
	return body.split('\n').filter((l) => l !== '');
}

test('the crawl rules are the ones static/robots.txt carried', () => {
	assert.deepEqual(directives(buildRobotsTxt('https://threkir.com')).slice(0, -1), [
		'User-agent: *',
		'Allow: /',
		'Disallow: /dashboard',
		'Disallow: /settings',
		'Disallow: /coach',
		'Disallow: /plans',
		'Disallow: /runs',
		'Disallow: /clubs',
		'Disallow: /help',
		'Disallow: /nutrition',
		'Disallow: /auth',
	]);
	assert.equal(ROBOTS_DISALLOW.length, 9);
});

test('the Sitemap line is an absolute URL on the given origin', () => {
	const last = directives(buildRobotsTxt('https://threkir.com')).at(-1)!;
	assert.equal(last, 'Sitemap: https://threkir.com/sitemap.xml');
	const url = new URL(last.replace(/^Sitemap:\s*/, ''));
	assert.equal(url.protocol, 'https:');
	assert.equal(url.pathname, '/sitemap.xml');
});

test('a trailing slash on the origin does not double the separator', () => {
	assert.ok(
		buildRobotsTxt('https://threkir.com/').split('\n').includes('Sitemap: https://threkir.com/sitemap.xml'),
	);
});

test('an unset or blank PUBLIC_SITE_URL builds on the apex, never www', () => {
	for (const configured of [undefined, '', '   ']) {
		const body = buildRobotsTxt(siteOrigin(configured));
		assert.ok(body.split('\n').includes(`Sitemap: ${DEFAULT_SITE_URL}/sitemap.xml`));
		assert.equal(new URL(DEFAULT_SITE_URL).hostname.startsWith('www.'), false);
		assert.ok(!body.includes('www.'));
	}
});

test('the body ends in a newline and has exactly one Sitemap line', () => {
	const body = buildRobotsTxt('https://threkir.com');
	assert.ok(body.endsWith('\n'));
	assert.equal(body.match(/^Sitemap:/gm)?.length, 1);
});

test('robots.txt is generated by the route, not shadowed by a static file', () => {
	assert.ok(existsSync(resolve(webRoot, 'src/routes/robots.txt/+server.ts')));
	assert.ok(
		!existsSync(resolve(webRoot, 'static/robots.txt')),
		'static/robots.txt would be served in place of the generated file under vite dev, with a relative Sitemap line',
	);
});
