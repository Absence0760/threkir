      fontFamily: fontFamily,
      package: 'ui_kit',
      scaffoldBackgroundColor: night,
      useMaterial3: true,
      splashFactory: InkRipple.splashFactory,
      // A shadow is not available against night, so dark carries the whole
      // separation in the fill: rising to nightHigh is a 1.19:1 step.
      appBarTheme: AppBarThemeData(
