// Unit tests for scripts/gen_edge_segment_matcher.mjs, the generator that
// bundles the web catalogue-segment matcher into the `segment-match` Edge
// Function (decisions § 2393). Needs apps/web's esbuild, so CI runs it after
// the dependency install in `parity-types`.
//
//   node --test scripts/gen_edge_segment_matcher.test.mjs

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

import { OUTPUT, buildMatcher } from './gen_edge_segment_matcher.mjs';

const SCRIPT = fileURLToPath(new URL('./gen_edge_segment_matcher.mjs', import.meta.url));

test('the bundle carries its do-not-edit header and exports what the function imports', async () => {
	const text = await buildMatcher();
	assert.ok(text.startsWith('// GENERATED by scripts/gen_edge_segment_matcher.mjs'), 'header first');
	for (const name of ['computeGlobalSegmentEfforts', 'globalSegmentGeometry', 'parseCourseCheckpoints', 'trackExtent']) {
		assert.match(text, new RegExp(`\\b${name}\\b`), `${name} is exported`);
	}
	assert.doesNotMatch(text, /from ['"]#lib\//, 'no import is left for the Edge runtime to resolve');
});

test('two builds of the same source are byte-identical, so the freshness check cannot flap', async () => {
	assert.equal(await buildMatcher(), await buildMatcher());
});

test('--check passes on the committed bundle and names the fix when it is stale', async () => {
	const committed = readFileSync(OUTPUT, 'utf8');
	const fresh = await buildMatcher();
	const run = spawnSync(process.execPath, [SCRIPT, '--check'], { encoding: 'utf8' });
	if (committed === fresh) {
		assert.equal(run.status, 0, run.stderr);
	} else {
		assert.equal(run.status, 1);
		assert.match(run.stderr, /pnpm gen:edge-segment-matcher/);
	}
});
