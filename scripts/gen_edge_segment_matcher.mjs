#!/usr/bin/env node
// Bundles the canonical catalogue-segment matcher into the `segment-match`
// Edge Function (issue #1313 Phase 1, decisions § 2392).
//
// The matcher is a TS↔Dart parity pair (`segments`, docs/architecture/
// parity_pairs.md) whose TS side lives in apps/web/src/lib. An Edge Function
// cannot import from that tree at run time — the deploy bundler sees only
// apps/backend — and a hand copy, or a Go port in the job worker, would be a
// third implementation for the pair to drift from. So the function runs the
// web module itself, bundled by esbuild (apps/web pins the version) into one
// generated file:
//
//   apps/backend/supabase/functions/_shared/segment_matcher.generated.js
//
// The entry exports exactly what the function needs: the catalogue sweep, the
// park-course checkpoint parser (so a malformed list fails closed the same way
// on both sides) and the track extent the candidates are chosen by.
// apps/web/src/lib/segments/edge_matcher_bundle.test.ts rebuilds the file and
// fails the web unit suite when it differs from the committed one, so an edit
// to the matcher that skips this step cannot merge.
//
//   node scripts/gen_edge_segment_matcher.mjs           rewrite the file
//   node scripts/gen_edge_segment_matcher.mjs --check   exit 1 if it is stale

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const WEB_LIB = join(REPO_ROOT, 'apps', 'web', 'src', 'lib');
export const OUTPUT = join(
	REPO_ROOT,
	'apps',
	'backend',
	'supabase',
	'functions',
	'_shared',
	'segment_matcher.generated.js',
);

const ENTRY = [
	"export { computeGlobalSegmentEfforts } from './segments/segments';",
	"export { parseCourseCheckpoints } from './parks/park_courses';",
	"export { trackExtent } from './segments/track_extent';",
	'',
].join('\n');

const HEADER = [
	'// GENERATED by scripts/gen_edge_segment_matcher.mjs from apps/web/src/lib',
	'// (segments/segments.ts, segments/track_extent.ts, parks/park_courses.ts and what',
	'// they import). Do not edit: change the web module, then run',
	'// `pnpm gen:edge-segment-matcher`.',
	'',
].join('\n');

/**
 * @typedef {{
 *   build(options: Record<string, unknown>): Promise<{ outputFiles: { text: string }[] }>
 * }} Esbuild
 */

/** @returns {Promise<string>} the file's full contents */
export async function buildMatcher() {
	const require = createRequire(join(REPO_ROOT, 'apps', 'web', 'package.json'));
	/** @type {Esbuild} */
	const esbuild = require('esbuild');
	const result = await esbuild.build({
		stdin: {
			contents: ENTRY,
			resolveDir: WEB_LIB,
			sourcefile: 'segment_matcher_entry.ts',
			loader: 'ts',
		},
		bundle: true,
		format: 'esm',
		platform: 'neutral',
		target: 'es2022',
		write: false,
		legalComments: 'none',
		charset: 'utf8',
		tsconfigRaw: {},
		absWorkingDir: REPO_ROOT,
	});
	return HEADER + result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const next = await buildMatcher();
	if (process.argv.includes('--check')) {
		let current = '';
		try {
			current = readFileSync(OUTPUT, 'utf8');
		} catch {
			current = '';
		}
		if (current !== next) {
			console.error(
				`${OUTPUT} is stale. Run: pnpm gen:edge-segment-matcher (node scripts/gen_edge_segment_matcher.mjs) and commit it.`,
			);
			process.exit(1);
		}
		console.log('segment_matcher.generated.js is current');
	} else {
		writeFileSync(OUTPUT, next);
		console.log(`wrote ${OUTPUT}`);
	}
}
